#!/usr/bin/env python3
"""Generate GRAPH.md and docs/nodes/*.md from the node metadata.

Reads every RNSNetwork/Nodes/<Node>/formalization.yaml, and the claim text
from each built node's Conclusions.lean, then writes:

  GRAPH.md               the network: diagrams, what rests on what, trust
  docs/nodes/README.md   index of node pages
  docs/nodes/<Node>.md   one page per node

Run from the repository root:   python scripts/graph.py
Needs Python 3 and PyYAML (pip install pyyaml). The output files are
generated: edit the yaml or Lean files and re-run, never the output.
"""
import glob
import os
import re
import sys

import yaml

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
NODES = os.path.join(ROOT, "RNSNetwork", "Nodes")
GENERATED = "**Generated file — do not edit.** Regenerated by `python scripts/graph.py`."
# Diagram boxes link here. GitHub draws Mermaid diagrams in a sandbox, so
# links inside them must be full URLs, not relative paths.
REPO_URL = "https://github.com/golfbum71/RNS-Sieve-Network/blob/main"


def page_url(node, claim=None):
    url = f"{REPO_URL}/docs/nodes/{node}.md"
    return url + (f"#{claim.lower()}" if claim else "")


# ---------------------------------------------------------------- loading

def load_nodes():
    nodes = {}
    for path in sorted(glob.glob(os.path.join(NODES, "*", "formalization.yaml"))):
        name = os.path.basename(os.path.dirname(path))
        data = yaml.safe_load(open(path, encoding="utf-8"))
        meta = data["node"]
        node = {
            "name": name,
            "order": meta.get("order", 999),
            "title": meta.get("title", ""),
            "description": " ".join(str(meta.get("description", "")).split()),
            "built": meta.get("status") == "active",
            "conclusions": data.get("conclusions") or [],
            "planned": data.get("planned") or {},
            "sources": data.get("sources") or [],
            # What the node adds over the nodes it builds on (optional).
            "improves": " ".join(str(meta.get("improves", "") or "").split()),
            # Nodes it is related to without resting on them: [{node, note}] (optional).
            "related": data.get("related") or [],
        }
        node["statements"] = read_statements(name) if node["built"] else {}
        nodes[name] = node
    return nodes


def read_statements(name):
    """Map each claim name to its docstring + Lean `def`, from Conclusions.lean."""
    path = os.path.join(NODES, name, "Conclusions.lean")
    text = open(path, encoding="utf-8").read()
    out = {}
    pattern = re.compile(
        r"(/--.*?-/\s*(?:noncomputable\s+)?def\s+(\w+)\b.*?)(?=\n\s*\n|\nend\s)", re.S)
    for match in pattern.finditer(text):
        out[match.group(2)] = match.group(1).strip()
    return out


def node_of(ref):
    """'CRT.v1.crt_map_bijective' -> ('CRT', 'crt_map_bijective')."""
    parts = ref.split(".")
    return parts[0], parts[-1]


def designated(c):
    return next((j for j in c.get("justifications") or [] if j["id"] == c.get("designated")), {})


def is_cited(c):
    return designated(c).get("kind") == "literature"


def is_draft(c):
    """A proof written but not yet built: shown as a draft, never as proved."""
    return designated(c).get("kind") == "lean-draft"


def is_project_file(s):
    """A `sources` entry naming one of the project's own Lean files, not a publication."""
    return s.get("relationship") == "formalizes"


def published_sources(n):
    return [s for s in n["sources"] if not is_project_file(s)]


def source_link(s):
    """Markdown for one published source: authors, linked title, and how the node uses it."""
    authors = s.get("authors") or []
    title = s.get("title", "")
    text = f"[{title}]({s['url']})" if s.get("url") else title
    if authors:
        text = ", ".join(authors) + ", " + text
    if s.get("relationship"):
        text += f" — {s['relationship']}"
    return text


def sources_section(n):
    """The 'Published sources' block shown near the top of every node page."""
    pubs = published_sources(n)
    if not pubs:
        return ""
    md = ("## Published sources\n\n"
          "Published work this node rests on or relates to; each entry says how.\n\n")
    md += "".join(f"- {source_link(s)}\n" for s in pubs)
    return md + "\n"


def opens_of(n):
    """Open conjectures a node takes as hypotheses (built or planned)."""
    out = []
    for c in n["conclusions"]:
        for o in c.get("open_inputs") or []:
            if o not in out:
                out.append(o)
    for o in n["planned"].get("open_inputs") or []:
        if o not in out:
            out.append(o)
    return out


def edges_built(nodes):
    """(source node, target node) -> list of (source claim, target claim)."""
    edges = {}
    for n in nodes.values():
        for c in n["conclusions"]:
            for ref in c.get("imports") or []:
                src, claim = node_of(ref)
                edges.setdefault((src, n["name"]), []).append((claim, c["id"]))
    return edges


def by_order(nodes):
    return sorted(nodes, key=lambda nm: nodes[nm]["order"])


def topo_order(nodes, edges):
    deps = {n: set() for n in nodes}
    for (src, dst) in edges:
        deps[dst].add(src)
    for n in nodes.values():
        for src in n["planned"].get("rests_on") or []:
            deps[n["name"]].add(src)
    order, done = [], set()

    def visit(name):
        if name in done:
            return
        done.add(name)
        for d in sorted(deps[name], key=lambda nm: nodes[nm]["order"] if nm in nodes else 999):
            if d in nodes:
                visit(d)
        order.append(name)

    for name in by_order(nodes):
        visit(name)
    return order


# ---------------------------------------------------------------- status

def node_kind(n):
    """One of: verified, conditional_built, cited_built, planned, conditional, cited, new, external."""
    if n["built"]:
        if any(is_draft(c) for c in n["conclusions"]):
            return "draft"
        if any(is_cited(c) for c in n["conclusions"]):
            return "cited_built"
        if opens_of(n):
            return "conditional_built"
        return "verified"
    return {"Conditional": "conditional", "Cited": "cited", "New": "new",
            "External": "external"}.get(n["planned"].get("source_status"), "planned")


STATUS_WORDS = {
    "verified": "proved in Lean",
    "conditional_built": "proved in Lean; rests on open conjectures as hypotheses",
    "cited_built": "cited from a published paper; not proved in Lean",
    "draft": "proof drafted, not yet built",
    "planned": "planned: proved in source file",
    "conditional": "planned: conditional",
    "cited": "planned: cited from a paper",
    "new": "planned: new, not yet proved",
    "external": "outside source: proved in Lean in another project",
}


def status_word(n):
    return STATUS_WORDS[node_kind(n)]


def claim_word(c):
    if is_cited(c):
        return "cited"
    if is_draft(c):
        return "proof drafted, not yet built"
    if c.get("open_inputs"):
        return "proved in Lean, assuming open conjecture(s)"
    return "proved in Lean"


def mid(name):
    return "N_" + name


def label(text):
    return text.replace('"', "'")


CLASSDEFS = """  classDef verified fill:#dafbe1,stroke:#1a7f37,color:#1f2328;
  classDef conditional_built fill:#dafbe1,stroke:#9a6700,color:#1f2328,stroke-width:2px;
  classDef cited_built fill:#ddf4ff,stroke:#0969da,color:#1f2328;
  classDef planned fill:#ffffff,stroke:#1a7f37,color:#57606a,stroke-dasharray: 5 4;
  classDef conditional fill:#ffffff,stroke:#9a6700,color:#57606a,stroke-dasharray: 5 4;
  classDef cited fill:#ffffff,stroke:#0969da,color:#57606a,stroke-dasharray: 5 4;
  classDef new fill:#ffffff,stroke:#57606a,color:#57606a,stroke-dasharray: 5 4;
  classDef draft fill:#ffffff,stroke:#1a7f37,color:#1f2328,stroke-width:2px,stroke-dasharray: 2 2;
  classDef external fill:#fbefff,stroke:#8250df,color:#1f2328;
  classDef openconj fill:#fff8c5,stroke:#9a6700,color:#1f2328;"""

KINDS = ["verified", "conditional_built", "cited_built", "draft", "planned", "conditional", "cited", "new",
         "external"]


# ---------------------------------------------------------------- GRAPH.md

def network_mermaid(nodes, order):
    """The whole network as one diagram: one panel per node, one clickable
    box per claim inside it, arrows from claim to claim, and open conjectures
    as hexagons pointing at the claims that assume them."""
    lines = ["```mermaid", "graph LR"]
    opens = []
    # Mermaid on GitHub refuses diagrams over 50,000 characters, so every box
    # gets a short ID (s1, c1, p1, o1, ...) instead of one spelled from its
    # node and claim names. The labels and links are unchanged.
    short = {}

    def sid(prefix, key):
        if (prefix, key) not in short:
            short[(prefix, key)] = f"{prefix}{sum(1 for k in short if k[0] == prefix) + 1}"
        return short[(prefix, key)]

    def C(nm, cl):
        return sid("c", (nm, cl))

    def S(nm):
        return sid("s", nm)

    def P(nm):
        return sid("p", nm)

    def O(o):
        return sid("o", o)
    for name in order:
        n = nodes[name]
        title = label(f"{n['order']}. {name} — {n['title']}")
        lines.append(f'  subgraph {S(name)}["<b>{title}</b>"]')
        if n["built"]:
            for c in n["conclusions"]:
                lines.append(f'    {C(name, c["id"])}["{c["id"]}"]')
                for o in c.get("open_inputs") or []:
                    if o not in opens:
                        opens.append(o)
        elif node_kind(n) == "external":
            project = n["planned"].get("external", {}).get("project", "another project")
            lines.append(f'    {P(name)}["<i>outside source: {label(project)}</i>"]')
        else:
            lines.append(f'    {P(name)}["<i>{status_word(n)}</i>"]')
        lines.append("  end")
    for o in opens:
        lines.append(f'  {O(o)}{{{{"<i>open conjecture</i><br/>{o}"}}}}')
    for name in order:
        n = nodes[name]
        for c in n["conclusions"]:
            for ref in c.get("imports") or []:
                src, claim = node_of(ref)
                lines.append(f"  {C(src, claim)} ==> {C(name, c['id'])}")
            for o in c.get("open_inputs") or []:
                lines.append(f"  {O(o)} -.-> {C(name, c['id'])}")
        for src in n["planned"].get("rests_on") or []:
            lines.append(f"  {S(src)} -.-> {S(name)}")
    lines.append(CLASSDEFS)
    groups = {k: [] for k in KINDS}
    for nm in order:
        n = nodes[nm]
        if not n["built"]:
            groups[node_kind(n)].append(P(nm))
            continue
        for c in n["conclusions"]:
            key = ("cited_built" if is_cited(c) else
                   "draft" if is_draft(c) else
                   "conditional_built" if c.get("open_inputs") else "verified")
            groups[key].append(C(nm, c['id']))
    for cls, ids in groups.items():
        if ids:
            lines.append(f"  class {','.join(ids)} {cls};")
    if opens:
        lines.append(f"  class {','.join(O(o) for o in opens)} openconj;")
    for nm in order:
        n = nodes[nm]
        if n["built"]:
            for c in n["conclusions"]:
                lines.append(f'  click {C(nm, c["id"])} href "{page_url(nm, c["id"])}" _blank')
        else:
            lines.append(f'  click {P(nm)} href "{page_url(nm)}" _blank')
    lines.append("```")
    return "\n".join(lines)


def rests_on_tree(nodes):
    imported = set()
    for n in nodes.values():
        for c in n["conclusions"]:
            for ref in c.get("imports") or []:
                imported.add(node_of(ref))
    out = []

    def walk(name, claim, depth):
        c = next(x for x in nodes[name]["conclusions"] if x["id"] == claim)
        link = f"[`{name}.{claim}`](docs/nodes/{name}.md#{claim.lower()})"
        out.append("  " * depth + f"- {link} — {claim_word(c)}")
        for o in c.get("open_inputs") or []:
            out.append("  " * (depth + 1) + f"- `{o}` — open conjecture, taken as a hypothesis")
        for ref in c.get("imports") or []:
            walk(*node_of(ref), depth + 1)

    for name in by_order(nodes):
        for c in nodes[name]["conclusions"]:
            if (name, c["id"]) not in imported:
                walk(name, c["id"], 0)
    return "\n".join(out)


def write_graph(nodes, order, edges):
    built = [nm for nm in order if nodes[nm]["built"]]
    planned = [nm for nm in order if not nodes[nm]["built"]]
    all_claims = [(nm, c) for nm in built for c in nodes[nm]["conclusions"]]
    n_lean = sum(1 for _, c in all_claims if not is_cited(c) and not is_draft(c))
    n_draft = sum(1 for _, c in all_claims if is_draft(c))
    n_cited = sum(1 for _, c in all_claims if is_cited(c))
    n_arrows = sum(len(p) for p in edges.values())
    built_opens = []
    for nm in built:
        for o in opens_of(nodes[nm]):
            if o not in built_opens:
                built_opens.append(o)

    standing = (f"**Where things stand:** {len(built)} of {len(nodes)} nodes are built, holding "
                f"{len(all_claims)} claims: {n_lean} proved in Lean"
                + (f", {n_draft} with a proof drafted but not yet built" if n_draft else "")
                + (f" and {n_cited} cited from a published paper" if n_cited else "")
                + f". They are joined by {n_arrows} arrows, each a Lean-checked step.")
    if planned:
        counts = {}
        for nm in planned:
            counts[node_kind(nodes[nm])] = counts.get(node_kind(nodes[nm]), 0) + 1
        parts = []
        for kind, one, many in [
                ("planned", "is proved in the original source files but not yet restated here",
                 "are proved in the original source files but not yet restated here"),
                ("conditional", "is a planned step that will assume an open conjecture",
                 "are planned steps that will assume open conjectures"),
                ("cited", "is a planned citation of a published result",
                 "are planned citations of published results"),
                ("new", "is new work, stated or scoped but not yet proved",
                 "are new work, stated or scoped but not yet proved"),
                ("external", "is an outside source, proved in Lean in another project and cited here",
                 "are outside sources, proved in Lean in other projects and cited here")]:
            k = counts.get(kind, 0)
            if k:
                parts.append(f"{k} {one if k == 1 else many}")
        standing += (f" Of the other {len(planned)} nodes, drawn dashed or purple, "
                     + "; ".join(parts) + ".")

    md = f"""# The network

{GENERATED}

This is a map of a Lean 4 / Mathlib formalization of a residue-number-system
(RNS) wheel sieve for primes. Each **node** is a group of related claims.
For each claim the network records what it says, what other claims it rests
on, and how it is justified. You can read off what any result depends on
without opening a single proof.

{standing}

## How to read the graph

- **Each panel is a node** — a group of related results, numbered and named.
  **Each box inside it is one claim.** Click a box to open that claim: its
  exact Lean statement, what it rests on, and where its proof lives.
- **Green box:** proved in Lean. Every proof uses only the standard axioms
  `propext`, `Classical.choice` and `Quot.sound`.
- **White box with a dotted green border:** a proof is drafted but has not
  yet been built with `lake build`; not counted as proved.
- **Green box with an amber border:** proved in Lean, but the claim is an
  implication whose hypotheses include an open conjecture. What is proved is
  "if the conjecture holds, then …" — never the conjecture.
- **Blue box:** cited from a published paper; stated precisely in Lean but
  not proved there.
- **Yellow hexagon:** an open conjecture. It is never claimed; the dotted
  arrow shows which claim assumes it as a hypothesis.
- **Thick arrow `A ==> B`:** claim B assumes claim A, and Lean checks the
  step. Each proof file imports only claims, never another node's proof;
  each arrow is proved as a separate `…_step` theorem with the upstream claim
  as a named hypothesis, and `RNSSolutions/Assemble.lean` joins the steps up.
- **A panel with no arrows in or out** rests on nothing but Mathlib and the
  shared Vocabulary.
- **Dashed box or dotted arrow between panels:** planned, not yet built. A
  grey dashed box is new work begun in this repository.
- **Purple box:** an outside source — a result proved in Lean in another
  project, linked from its page. Nodes here cite it as a named hypothesis
  rather than re-proving it or importing that project.

## The network

{network_mermaid(nodes, order)}

## What each result rests on

The results nothing else builds on, each with everything beneath it.

{rests_on_tree(nodes)}

## What the network takes on trust

Every claim proved in Lean uses only the three standard axioms, and every
thick arrow is itself a Lean-checked step. Beyond that, the network relies on
exactly the following, each recorded as such rather than claimed:

"""
    if built_opens:
        md += "**Open conjectures, assumed only as hypotheses of claims:**\n\n"
        for o in built_opens:
            users = [f"[`{nm}.{c['id']}`](docs/nodes/{nm}.md#{c['id'].lower()})"
                     for nm in built for c in nodes[nm]["conclusions"]
                     if o in (c.get("open_inputs") or [])]
            md += f"- `{o}` — assumed by " + ", ".join(users) + "\n"
        md += "\n"
    cited = [(nm, c) for nm, c in all_claims if is_cited(c)]
    if cited:
        md += "**Published results, cited rather than proved in Lean:**\n\n"
        for nm, c in cited:
            j = designated(c)
            md += (f"- [`{nm}.{c['id']}`](docs/nodes/{nm}.md#{c['id'].lower()}) — "
                   f"{j.get('source', '')}, {j.get('locator', '')}\n")
        md += "\n"
    if not built_opens and not cited:
        md += "Nothing.\n\n"
    externals = [nm for nm in by_order(nodes) if node_kind(nodes[nm]) == "external"]
    if externals:
        md += "**Outside sources, proved in Lean elsewhere and cited here:**\n\n"
        for nm in externals:
            e = nodes[nm]["planned"].get("external", {})
            users = [m for m in by_order(nodes) if nm in (nodes[m]["planned"].get("rests_on") or [])]
            decl = f"`{e['declaration']}` in " if e.get("declaration") else ""
            md += f"- [`{nm}`](docs/nodes/{nm}.md) — {decl}[{e.get('project', '')}]({e.get('url', '')})"
            if users:
                md += " — cited by " + ", ".join(f"[`{u}`](docs/nodes/{u}.md)" for u in users)
            md += "\n"
        md += "\n"
    planned_opens = [o for nm in planned for o in opens_of(nodes[nm]) if o not in built_opens]
    if planned_opens:
        md += "**Planned nodes will add:** " + ", ".join(f"`{o}`" for o in planned_opens) + "\n\n"

    with_pubs = [nm for nm in by_order(nodes) if published_sources(nodes[nm])]
    if with_pubs:
        md += ("## Published sources\n\n"
               "Nodes that apply the RNS to published work: proven results, cited "
               "theorems, or stated conjectures, with links to the papers and pages. "
               "Each node's page lists the same sources at the top.\n\n")
        for nm in with_pubs:
            md += f"- [`{nm}`](docs/nodes/{nm}.md)\n"
            md += "".join(f"  - {source_link(s)}\n" for s in published_sources(nodes[nm]))
        md += "\n"

    md += "## Node index\n\n| # | Node | What it says | Status |\n|---|---|---|---|\n"
    for nm in by_order(nodes):
        n = nodes[nm]
        md += f"| {n['order']} | [`{nm}`](docs/nodes/{nm}.md) | {n['title']} | {status_word(n)} |\n"
    open(os.path.join(ROOT, "GRAPH.md"), "w", encoding="utf-8").write(md)


# ---------------------------------------------------------------- node pages

def related_section(n, nodes):
    """Nodes this one is related to without an arrow, each with a note on how."""
    if not n["related"]:
        return ""
    md = ("## Related nodes\n\nConnected in content but not by an arrow (no claim here "
          "takes theirs as a hypothesis); each entry says how.\n\n")
    for r in n["related"]:
        other = r.get("node", "")
        link = f"[`{other}`]({other}.md)" if other in nodes else f"`{other}`"
        md += f"- {link} — {' '.join(str(r.get('note', '')).split())}\n"
    return md + "\n"


def write_node_page(n, nodes, edges):
    name = n["name"]
    md = f"# {name} — {n['title']}\n\n{GENERATED}\n\n"
    md += f"**Status:** {status_word(n)}\n\n{n['description']}\n\n"
    if n["improves"]:
        md += f"**What it adds:** {n['improves']}\n\n"
    md += sources_section(n)
    md += related_section(n, nodes)
    if n["built"]:
        md += "## Claims\n\n"
        for c in n["conclusions"]:
            md += f'<a id="{c["id"].lower()}"></a>\n### `{c["id"]}`\n\n{c.get("summary", "")}\n\n'
            stmt = n["statements"].get(c["id"])
            if stmt:
                md += "```lean\n" + stmt + "\n```\n\n"
            imports = c.get("imports") or []
            if imports:
                md += "**Rests on:** " + ", ".join(
                    f"[`{s}.{cl}`]({s}.md#{cl.lower()})" for s, cl in map(node_of, imports)) + "\n\n"
            else:
                md += "**Rests on:** no other node (Mathlib and the Vocabulary only)\n\n"
            if c.get("open_inputs"):
                md += ("**Open conjectures in its hypotheses (assumed, never claimed):** "
                       + ", ".join(f"`{o}`" for o in c["open_inputs"]) + "\n\n")
            j = designated(c)
            if j.get("kind") == "literature":
                md += (f"**Justification:** cited — {j.get('source', '')}, "
                       f"{j.get('locator', '')}. Not proved in Lean.\n\n")
            elif j:
                md += (f"**Proof:** `{j.get('declaration')}` in "
                       f"[`{j.get('solution')}`](../../{j.get('solution')})")
                if j.get("assembled"):
                    md += ("; joined to its inputs in "
                           "[`RNSSolutions/Assemble.lean`](../../RNSSolutions/Assemble.lean)")
                md += "\n\n"
        users = sorted({dst for (src, dst) in edges if src == name},
                       key=lambda u: nodes[u]["order"])
        users += [m["name"] for m in nodes.values()
                  if name in (m["planned"].get("rests_on") or [])]
        if users:
            md += "## Used by\n\n" + "\n".join(f"- [`{u}`]({u}.md)" for u in users) + "\n\n"
        md += (f"## Files\n\n- Claims: [`Conclusions.lean`](../../RNSNetwork/Nodes/{name}/Conclusions.lean)\n"
               f"- Metadata: [`formalization.yaml`](../../RNSNetwork/Nodes/{name}/formalization.yaml)\n")
        for s in n["sources"]:
            if is_project_file(s):
                md += f"- Original source file: {s.get('title')}\n"
    else:
        p = n["planned"]
        rests = p.get("rests_on") or []
        if node_kind(n) == "external":
            md += "## Outside source\n\n"
        else:
            md += "## Planned\n\n"
            md += "**Will rest on:** " + (", ".join(f"[`{r}`]({r}.md)" for r in rests)
                                          or "no other node") + "\n\n"
        if p.get("open_inputs"):
            md += "**Open conjectures it will take as named hypotheses:** " + ", ".join(
                f"`{o}`" for o in p["open_inputs"]) + "\n\n"
        if p.get("source_declarations"):
            md += f"**In the source files:** {' '.join(str(p['source_declarations']).split())}\n\n"
        if p.get("external"):
            e = p["external"]
            decl = f"`{e['declaration']}` in " if e.get("declaration") else ""
            md += f"**Outside source:** {decl}[{e.get('project', '')}]({e.get('url', '')})"
            if e.get("toolchain"):
                md += f" (built on {e['toolchain']})"
            md += ".\n\n"
            if e.get("note"):
                md += f"{' '.join(str(e['note']).split())}\n\n"
        if p.get("claims"):
            md += "**Planned claims:** " + ", ".join(f"`{c}`" for c in p["claims"]) + "\n\n"
        for key, title in [("progress", "Progress"), ("plan", "Plan"), ("evidence", "Evidence so far"),
                           ("tier", "Scope")]:
            if p.get(key):
                md += f"**{title}:** {' '.join(str(p[key]).split())}\n\n"
        users = [m["name"] for m in nodes.values() if name in (m["planned"].get("rests_on") or [])]
        if users:
            md += "**Cited by:** " + ", ".join(f"[`{u}`]({u}.md)" for u in sorted(
                users, key=lambda u: nodes[u]["order"])) + "\n\n"
        if p.get("citation"):
            md += f"**Citation:** {' '.join(str(p['citation']).split())}\n\n"
    open(os.path.join(ROOT, "docs", "nodes", f"{name}.md"), "w", encoding="utf-8").write(md)


def write_index(nodes):
    md = f"# Node pages\n\n{GENERATED}\n\n| # | Node | What it says | Status |\n|---|---|---|---|\n"
    for nm in by_order(nodes):
        n = nodes[nm]
        md += f"| {n['order']} | [`{nm}`]({nm}.md) | {n['title']} | {status_word(n)} |\n"
    md += "\nSee [`GRAPH.md`](../../GRAPH.md) for the diagrams.\n"
    open(os.path.join(ROOT, "docs", "nodes", "README.md"), "w", encoding="utf-8").write(md)


def main():
    nodes = load_nodes()
    edges = edges_built(nodes)
    for (src, dst) in edges:
        if src not in nodes or not nodes[src]["built"]:
            sys.exit(f"error: {dst} imports from {src}, which is not a built node")
    for n in nodes.values():
        for c in n["conclusions"]:
            for ref in c.get("imports") or []:
                src, claim = node_of(ref)
                if claim not in {x["id"] for x in nodes[src]["conclusions"]}:
                    sys.exit(f"error: {n['name']}.{c['id']} imports {ref}, which does not exist")
            if n["built"] and c["id"] not in n["statements"]:
                sys.exit(f"error: {n['name']}.{c['id']} has no matching def in Conclusions.lean")
    order = topo_order(nodes, edges)
    os.makedirs(os.path.join(ROOT, "docs", "nodes"), exist_ok=True)
    write_graph(nodes, order, edges)
    for n in nodes.values():
        write_node_page(n, nodes, edges)
    write_index(nodes)
    print(f"wrote GRAPH.md and {len(nodes)} node pages")


if __name__ == "__main__":
    main()
